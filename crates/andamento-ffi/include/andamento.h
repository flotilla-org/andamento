/*
 * Andamento's C ABI. docs/sidebar-design/host-interface.md describes it as
 * a whole; each declaration's comment gives its contract.
 *
 * Calls on one sidebar are serialised by the host. Input pointers and
 * arrays are borrowed for the call only; NULL input pointers require zero
 * length, and others must be valid and aligned for their length. Handles
 * are live allocations from this library, or NULL; never use one after
 * releasing it. Tags are uint32_t, not C enums.
 *
 * A call that mutates returns 1 on success and 0 on error, and changes
 * nothing on invalid input. error_out, when not NULL, is cleared on entry
 * and receives an owned NUL-terminated message on error; free it with
 * andamento_string_free. A panic poisons the sidebar: destroy and recreate
 * it. Getters return 0 for NULL handles or output and for invalid indices,
 * leaving the output untouched.
 */

